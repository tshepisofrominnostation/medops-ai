"""Executive narrative: LLM rewording of verified findings, with a hard grounding check.

Two engines behind one function, `write_narrative`:
  1. DeterministicNarrative - always available, offline, never invents a number.
  2. LLMNarrative - optional OpenAI-compatible model (MEDOPS_LLM_* variables, the
     same ones the reply writer uses).

Responsible-AI controls (Week 4 rubric: "responsible AI use")
  - The model only REWORDS findings produced by app/insights.py. It is never given raw
    tickets, so no patient text can leave the network through this path.
  - GROUNDING: every number in the model's output must appear in the supplied
    findings. One unsupported figure rejects the whole output and the deterministic
    narrative is used instead.
  - The compliance screen runs over the final text, whichever engine wrote it.
  - The result always states which engine wrote it and carries a disclosure line.
  - Any failure (timeout, HTTP error, bad JSON, grounding breach) falls back silently
    to the deterministic engine. Reporting never fails because a model did.
"""
import json
import os
import re
from typing import Optional

from ..compliance import screen

DISCLOSURE = ("Generated by MedOps AI from recorded ticket data. Figures are computed; "
              "wording may be AI-assisted. Review before circulating.")

MIN_DAYS_FOR_QUOTED_ERROR = 14

_NUM = re.compile(r"\d+(?:\.\d+)?")


def _numbers_in(text: str) -> set[str]:
    return {n.rstrip("0").rstrip(".") if "." in n else n for n in _NUM.findall(text)}


def allowed_numbers(insights: dict) -> set[str]:
    """Every number legitimately present in the findings and their evidence."""
    # The forecast is legitimate source material: the narrative is allowed to quote
    # its totals, horizon and error. Anything outside this pool is an invention.
    pool = json.dumps({"f": insights.get("findings", []),
                       "w": insights.get("window"), "pw": insights.get("previous_window"),
                       "s": insights.get("scope"),
                       "fc": insights.get("forecast")}, default=str)
    nums = _numbers_in(pool)
    # percentages and rounded forms of evidence values are legitimate restatements
    for f in insights.get("findings", []):
        for v in (f.get("evidence") or {}).values():
            if isinstance(v, float):
                nums |= _numbers_in(f"{v * 100:.0f} {v * 100:.1f} {v:.2f} {v:.1f} {v:.0f}")
            if isinstance(v, dict):
                for x in v.values():
                    if isinstance(x, (int, float)):
                        nums |= _numbers_in(f"{x * 100:.0f} {x}")
    # calendar tokens inside ISO dates are fine
    return nums


def ungrounded_numbers(text: str, insights: dict) -> list[str]:
    ok = allowed_numbers(insights)
    # dates like 2026-11-06 contribute 2026, 11, 06
    extra = set()
    for d in re.findall(r"\d{4}-\d{2}-\d{2}", json.dumps(insights.get("window", {}))
                        + json.dumps(insights.get("previous_window", {}))):
        extra |= _numbers_in(d.replace("-", " "))
    return sorted(n for n in _numbers_in(text) if n not in ok and n not in extra)


def fmt_minutes(m) -> str:
    """One duration format for the whole product (KPI tiles, tables and prose)."""
    if m is None:
        return "n/a"
    if m < 60:
        return f"{m:.0f} min"
    h, rem = divmod(m, 60)
    return f"{int(h)} h {int(rem)} min" if round(rem) >= 1 else f"{int(h)} h"


def _join(items: list[str]) -> str:
    items = list(items)
    if len(items) <= 1:
        return "".join(items)
    if len(items) == 2:
        return f"{items[0]} and {items[1]}"
    return ", ".join(items[:-1]) + f" and {items[-1]}"


class DeterministicNarrative:
    """Prose built only from the findings. Never adds a number the findings lack."""
    name = "deterministic"

    def write(self, insights: dict) -> str:
        by_kind = {f["kind"]: f for f in insights["findings"]}
        w = insights["window"]
        scope = insights["scope"]
        if "empty" in by_kind:
            return f"No tickets were logged for {scope} between {w['start']} and {w['end']}."

        para = []
        # 1. Volume and mix
        vt, tc = by_kind.get("volume_trend"), by_kind.get("top_category")
        s1 = vt["headline"] if vt else ""
        if tc:
            s1 += (" " if s1 else "") + tc["headline"]
        para.append(s1)

        # 2. Pressure
        pp = by_kind.get("priority_pressure")
        if pp:
            para.append(pp["headline"])

        # 3. Service performance
        rt, sla, gap = by_kind.get("response_time"), by_kind.get("sla"), by_kind.get("sla_gap")
        perf = []
        if rt:
            perf.append(rt["headline"])
        if sla:
            perf.append(sla["headline"])
        if gap:
            ev = gap["evidence"]
            bits = []
            if ev["behind"]:
                bits.append("well below target for " + _join(ev["behind"]) + " priority tickets")
            if ev["watch"]:
                bits.append("close to target for " + _join(ev["watch"]) + " priority tickets")
            if bits:
                perf.append("Response performance was " + " and ".join(bits) + ".")
        if perf:
            para.append(" ".join(perf))

        # 4. Backlog and data quality
        tail = [by_kind[k]["headline"] for k in ("backlog", "data_quality") if k in by_kind]
        if tail:
            para.append(" ".join(tail))

        # 5. Outlook
        fc = insights.get("forecast")
        if fc and fc.get("forecast"):
            mae, days = fc.get("backtest_mae"), fc.get("history_days", 0)
            if days >= MIN_DAYS_FOR_QUOTED_ERROR and mae is not None:
                para.append(f"Outlook: about {fc['predicted_total']} tickets are expected over the "
                            f"next {fc['horizon']} days, with a backtest error of {mae} tickets per day. "
                            "This is a planning aid, not a prediction.")
            else:
                para.append(f"Outlook: about {fc['predicted_total']} tickets are expected over the "
                            f"next {fc['horizon']} days, but with only {days} day"
                            f"{'s' if days != 1 else ''} of history no error margin can be quoted. "
                            "Treat this as a planning aid, not a prediction.")
        return "\n".join(p for p in para if p)


class LLMNarrative:
    name = "llm"
    SYSTEM = (
        "You write a short executive summary of a hospital operations week for a department "
        "head. You are given a JSON list of verified findings. Rewrite them as 3 to 5 plain "
        "sentences in a calm professional tone. STRICT RULES: use only numbers that appear in "
        "the findings; do not add any new figure, name, cause or recommendation that is not in "
        "the findings; keep any caveat about thin data; never mention individual patients or "
        "staff. Output JSON: {\"summary\": \"...\"}."
    )

    def __init__(self):
        self.base_url = os.environ.get("MEDOPS_LLM_BASE_URL", "").rstrip("/")
        self.api_key = os.environ.get("MEDOPS_LLM_API_KEY", "")
        self.model = os.environ.get("MEDOPS_LLM_MODEL", "gpt-4o-mini")
        self.timeout = float(os.environ.get("MEDOPS_LLM_TIMEOUT", "12"))
        self.configured = bool(self.base_url and self.api_key)

    def write(self, insights: dict) -> Optional[str]:
        if not self.configured:
            return None
        try:
            import urllib.request
            payload = json.dumps({
                "model": self.model, "temperature": 0.2,
                "response_format": {"type": "json_object"},
                "messages": [
                    {"role": "system", "content": self.SYSTEM},
                    {"role": "user", "content": json.dumps({
                        "scope": insights["scope"], "window": insights["window"],
                        "findings": [{"headline": f["headline"], "confidence": f["confidence"]}
                                     for f in insights["findings"]]})},
                ]}).encode()
            req = urllib.request.Request(
                f"{self.base_url}/chat/completions", data=payload, method="POST",
                headers={"Content-Type": "application/json",
                         "Authorization": f"Bearer {self.api_key}"})
            with urllib.request.urlopen(req, timeout=self.timeout) as resp:
                body = json.loads(resp.read().decode())
            text = json.loads(body["choices"][0]["message"]["content"])["summary"]
            return text.strip() if isinstance(text, str) and text.strip() else None
        except Exception:
            return None


def write_narrative(insights: dict, llm: Optional[LLMNarrative] = None) -> dict:
    """Return {text, engine, grounded, rejected_reason, compliance, disclosure}."""
    llm = llm or LLMNarrative()
    fallback_reason = None
    text, engine = None, "deterministic"

    candidate = llm.write(insights) if llm.configured else None
    if llm.configured and candidate is None:
        fallback_reason = "llm unavailable or returned unusable output"
    if candidate:
        bad = ungrounded_numbers(candidate, insights)
        if bad:
            fallback_reason = f"llm introduced unsupported figures: {', '.join(bad)}"
        else:
            verdict = screen(candidate)
            if verdict["verdict"] == "blocked":
                fallback_reason = "llm output blocked by compliance screen"
            else:
                text, engine = candidate, "llm"

    if text is None:
        text = DeterministicNarrative().write(insights)

    final_screen = screen(text)
    return {
        "text": text,
        "engine": engine,
        "model": llm.model if engine == "llm" else None,
        "grounded": True,
        "fallback_reason": fallback_reason,
        "compliance": {"verdict": final_screen["verdict"], "counts": final_screen["counts"]},
        "disclosure": DISCLOSURE,
    }
